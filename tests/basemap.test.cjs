const { test } = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const vm = require("node:vm")
const geo = vm.createContext({})
vm.runInContext(fs.readFileSync(path.join(__dirname, "../Basemap.js"), "utf8"), geo)

test("the AWS image and the native raster describe the same Mercator rectangle", () => {
    const frame = geo.frameFor([{x: 15557000, y: 4257000}, {x: 15559000, y: 4258000}], 900, 450)
    const xml = geo.rasterSource(frame, "Standard", "ap-northeast-1", "key with &")
    assert.match(xml, /<Projection>EPSG:3857<\/Projection>/)
    assert.match(xml, /<Layer>Standard<\/Layer>/)
    assert.match(xml, /style=\$\{layer\}&amp;bounding-box=/)
    assert.match(xml, /key=key%20with%20%26/)
    const bbox = xml.match(/bounding-box=([^&<]+)/)[1].split(",").map(Number)
    assert.ok(bbox[0] > 139 && bbox[2] < 140 && bbox[1] > 35 && bbox[3] < 36)
    assert.ok(Math.abs((frame.east - frame.west) / frame.width - (frame.north - frame.south) / frame.height) < 1e-9)
    assert.ok(geo.covers(frame, frame.view))
    assert.ok(!geo.covers(frame, {...frame.view, east: frame.east + 1}))
    assert.ok(!geo.covers(frame, {...frame.view, resolution: frame.view.resolution / 2}))
})

test("invalid views are ignored and image sizes respect API bounds", () => {
    assert.equal(geo.frameFor([{x: NaN, y: 0}], 400, 400), null)
    assert.equal(geo.frameFor([{x: 0, y: 0}, {x: 2, y: 2}], 0, 400), null)
    const f = geo.frameFor([{x: 0, y: 0}, {x: 100, y: 5000}], 300, 3000)
    assert.ok(f.width >= 64 && f.height <= 1400)
})
